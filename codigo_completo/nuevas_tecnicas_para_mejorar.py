# 1. Función para visualizar la predicción y el Grad-CAM / Mapa de Calor
def explicar_prediccion_swin(ruta_imagen):
    model.eval()
    img_pil = Image.open(ruta_imagen).convert('RGB')

    transform_test = transforms.Compose([
        transforms.Resize((224, 224)),
        transforms.ToTensor(),
        transforms.Normalize(mean=[0.485, 0.456, 0.406], std=[0.229, 0.224, 0.225])
    ])

    input_tensor = transform_test(img_pil).unsqueeze(0).to(device)

    # Obtener activación de las últimas capas
    activation = {}
    def get_activation(name):
        def hook(model, input, output):
            activation[name] = output.detach()
        return hook

    # Registrar hook en el último bloque del Transformer
    model.layers[-1].blocks[-1].norm2.register_forward_hook(get_activation('last_layer'))

    with torch.no_grad():
        outputs = model(input_tensor)
        probabilities = torch.nn.functional.softmax(outputs[0], dim=0)

    prob_np = probabilities.cpu().numpy()
    pred_idx = np.argmax(prob_np)
    pred_class = class_names[pred_idx]

    # Procesar mapa de atención
    act = activation['last_layer'].squeeze(0) # [C, H, W] or [Patches, C]
    if len(act.shape) == 2:
        num_patches = act.shape[0]
        grid_size = int(np.sqrt(num_patches))
        cam = act.mean(dim=-1).reshape(grid_size, grid_size).cpu().numpy()
    else:
        cam = act.mean(dim=0).cpu().numpy()

    # Normalizar mapa de calor entre 0 y 1
    cam = (cam - cam.min()) / (cam.max() - cam.min() + 1e-8)

    # Redimensionar al tamaño original de la imagen
    img_orig = np.array(img_pil)
    h, w, _ = img_orig.shape
    cam_resized = cv2.resize(cam, (w, h))

    # Crear mapa de calor en RGB (JET)
    heatmap = cv2.applyColorMap(np.uint8(255 * cam_resized), cv2.COLORMAP_JET)
    heatmap_rgb = cv2.cvtColor(heatmap, cv2.COLOR_BGR2RGB)

    # Superposición
    overlay = cv2.addWeighted(img_orig, 0.6, heatmap_rgb, 0.4, 0)

    # Graficar
    fig, axes = plt.subplots(1, 3, figsize=(15, 5))
    axes[0].imshow(img_orig)
    axes[0].set_title("Imagen Entrante (Bokeh)", fontsize=12)
    axes[0].axis('off')

    axes[1].imshow(overlay)
    axes[1].set_title(f"Atención del Swin-T (Grad-CAM)", fontsize=12)
    axes[1].axis('off')

    y_pos = np.arange(len(class_names))
    axes[2].barh(y_pos, prob_np * 100, color='skyblue')
    axes[2].set_yticks(y_pos)
    axes[2].set_yticklabels(class_names)
    axes[2].set_xlabel('Confianza (%)')
    axes[2].set_title(f"Predicción: {pred_class} ({prob_np[pred_idx]*100:.1f}%)", fontsize=12)

    plt.tight_layout()
    plt.show()

