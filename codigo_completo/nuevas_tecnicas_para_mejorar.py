def aplicar_bokeh(img_path):
    img = cv2.imread(img_path)
    if img is None:
        return None

    h, w, _ = img.shape
    results = model_seg(img_path, verbose=False)[0]

    mask = np.zeros((h, w), dtype=np.float32)
    if results.masks is not None:
        for m in results.masks.data:
            m_np = m.cpu().numpy().astype(np.float32)
            m_resized = cv2.resize(m_np, (w, h))
            mask = np.maximum(mask, m_resized)

    # Crear fondo fuertemente desenfocado
    fondo_borroso = cv2.GaussianBlur(img, (99, 99), 0)

    # Suavizado de bordes de la máscara
    mask_soft = cv2.GaussianBlur(mask, (11, 11), 0)
    mask_3ch = np.repeat(mask_soft[:, :, np.newaxis], 3, axis=2)

    # Combinación: Hoja nítida + Fondo borroso
    resultado = (img * mask_3ch + fondo_borroso * (1.0 - mask_3ch)).astype(np.uint8)
    return resultado

