def explicar_prediccion_swin_exacto(ruta_imagen):
    model.eval()
    img_pil = Image.open(ruta_imagen).convert('RGB')

    transform_test = transforms.Compose([
        transforms.Resize((224, 224)),
        transforms.ToTensor(),
        transforms.Normalize(mean=[0.485, 0.456, 0.406], std=[0.229, 0.224, 0.225])
    ])

    input_tensor = transform_test(img_pil).unsqueeze(0).to(device)
    input_tensor.requires_grad_()

    # Captura de activaciones y gradientes mediante hooks
    gradients = []
    activations = []

    def save_gradient(grad):
        gradients.append(grad)

    def forward_hook(module, input, output):
        activations.append(output)
        output.register_hook(save_gradient)

    # Conectar en la última capa de normalización del Transformer
    target_layer = model.layers[-1].blocks[-1].norm2
    handle = target_layer.register_forward_hook(forward_hook)

    # Pasada hacia adelante (Forward Pass)
    outputs = model(input_tensor)
    probabilities = torch.nn.functional.softmax(outputs[0], dim=0)

    prob_np = probabilities.detach().cpu().numpy()
    pred_idx = np.argmax(prob_np)
    pred_class = class_names[pred_idx]

    # Retropropagación (Backward Pass) del gradiente de la clase predicha
    model.zero_grad()
    score = outputs[0, pred_idx]
    score.backward()

    # Desconectar el hook
    handle.remove()

    # Cálculo ponderado de características sintomáticas
    act = activations[0].detach().squeeze(0) # [Tokens, Canales]
    grad = gradients[0].detach().squeeze(0)  # [Tokens, Canales]

    weights = torch.mean(grad, dim=0)
    cam = torch.matmul(act, weights)
    cam = torch.relu(cam) # Filtra activaciones negativas

    # Reestructurar tokens a cuadrícula 2D
    num_patches = cam.shape[0]
    grid_size = int(np.sqrt(num_patches))
    cam = cam.reshape(grid_size, grid_size).cpu().numpy()

    # Suavizado y normalización
    cam = cv2.GaussianBlur(cam, (3, 3), 0)
    if cam.max() > 0:
        cam = cam / cam.max()

    # Redimensionar al tamaño nativo de la imagen
    img_orig = np.array(img_pil)
    h, w, _ = img_orig.shape
    cam_resized = cv2.resize(cam, (w, h))

    # Superposición de mapa de calor RGB
    heatmap = cv2.applyColorMap(np.uint8(255 * cam_resized), cv2.COLORMAP_JET)
    heatmap_rgb = cv2.cvtColor(heatmap, cv2.COLOR_BGR2RGB)
    overlay = cv2.addWeighted(img_orig, 0.65, heatmap_rgb, 0.35, 0)

    # Graficar resultados
    fig, axes = plt.subplots(1, 3, figsize=(15, 5))
    axes[0].imshow(img_orig)
    axes[0].set_title("Imagen Entrante (Bokeh)", fontsize=12)
    axes[0].axis('off')

    axes[1].imshow(overlay)
    axes[1].set_title("Grad-CAM Ponderado (Swin-T)", fontsize=12)
    axes[1].axis('off')

    y_pos = np.arange(len(class_names))
    axes[2].barh(y_pos, prob_np * 100, color='skyblue')
    axes[2].set_yticks(y_pos)
    axes[2].set_yticklabels(class_names)
    axes[2].set_xlabel('Confianza (%)')
    axes[2].set_title(f"Predicción: {pred_class} ({prob_np[pred_idx]*100:.1f}%)", fontsize=12)

    plt.tight_layout()
    plt.show()

