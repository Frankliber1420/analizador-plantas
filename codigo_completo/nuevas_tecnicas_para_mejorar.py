def procesar_imagen_bokeh(ruta_imagen, intensidad_desenfoque=(51, 51)):
    img = cv2.imread(ruta_imagen)
    if img is None:
        raise FileNotFoundError(f"No se pudo cargar la imagen: {ruta_imagen}")

    img_rgb = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)
    h, w, _ = img.shape

    # Inferencia
    results = model_seg(ruta_imagen, verbose=False)[0]

    mask = np.zeros((h, w), dtype=np.uint8)

    # Si el modelo tiene máscaras (segmentación)
    if results.masks is not None:
        for m in results.masks.data:
            m_np = m.cpu().numpy().astype(np.uint8)
            m_resized = cv2.resize(m_np, (w, h))
            mask = np.maximum(mask, m_resized)
    # Si el modelo detectó cajas (Bounding Boxes)
    elif results.boxes is not None:
        for box in results.boxes.xyxy.cpu().numpy():
            x1, y1, x2, y2 = map(int, box[:4])
            mask[y1:y2, x1:x2] = 1

    # 1. Fondo borroso por filtro gaussiano
    fondo_borroso = cv2.GaussianBlur(img_rgb, intensidad_desenfoque, 0)

    # 2. Suavizado de bordes para evitar artefactos
    mask_float = cv2.GaussianBlur(mask.astype(float), (15, 15), 0)
    mask_3ch = np.repeat(mask_float[:, :, np.newaxis], 3, axis=2)

    # 3. Mezcla: Palma nítida + Fondo desenfocado
    resultado_bokeh = (img_rgb * mask_3ch + fondo_borroso * (1.0 - mask_3ch)).astype(np.uint8)

    return img_rgb, resultado_bokeh

